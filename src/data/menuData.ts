export type Dish = {
  id: number | string;
  posMenuItemId?: number | null;
  name: string;
  price: number;
  category: string;
  description: string;
  rating: number;
  popular: boolean;
  image: string;
};

export const DEFAULT_CATEGORIES = [
  "All",
  "Main Course",
  "Beverage",
  "Burger",
  "Platters",
  "Combo",
  "Topping",
  "Fries",
];

export const categories = DEFAULT_CATEGORIES;

export function categoriesFrom(dishes: Dish[]) {
  const extra = [...new Set(dishes.map((dish) => dish.category))];
  const rest = extra.filter((name) => !DEFAULT_CATEGORIES.includes(name));
  return [...DEFAULT_CATEGORIES, ...rest];
}
